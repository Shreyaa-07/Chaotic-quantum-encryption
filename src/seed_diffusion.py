"""
Chaotic Seed Diffusion Module (Step 4 / PM2_2)
===============================================
Implements the final diffusion module as described in Section IV-E.

This module generates a random matrix S using the discretized Van der Pol
Oscillator and XORs it with the image output from Step 3.

From Eq. 32:
    |C⟩ = |S⟩ ⊕ |I₂⟩

where:
    - |S⟩ is the random diffusion matrix from Van der Pol
    - |I₂⟩ is the output of the selective shuffle (Step 3)
    - |C⟩ is the final cipher image

Since XOR is its own inverse, decryption uses the same operation.
"""

import numpy as np


def seed_diffusion_encrypt(image: np.ndarray,
                           diffusion_matrix: np.ndarray) -> np.ndarray:
    """
    Apply chaotic seed diffusion (encryption) via XOR with diffusion matrix.
    
    Parameters
    ----------
    image : ndarray, shape (H, W), dtype uint8
        Input image (output of Step 3).
    diffusion_matrix : ndarray, shape (H, W), dtype uint8
        Random matrix generated by Van der Pol oscillator.
    
    Returns
    -------
    cipher : ndarray, shape (H, W), dtype uint8
        Cipher image (XOR of input and diffusion matrix).
    """
    return np.bitwise_xor(image, diffusion_matrix)


def seed_diffusion_decrypt(cipher: np.ndarray,
                           diffusion_matrix: np.ndarray) -> np.ndarray:
    """
    Apply inverse chaotic seed diffusion (decryption).
    Since XOR is self-inverse, this is identical to encryption.
    """
    return np.bitwise_xor(cipher, diffusion_matrix)
